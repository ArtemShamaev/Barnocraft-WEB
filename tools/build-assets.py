#!/usr/bin/env python3
"""Regenerate js/assets.js: textures as data URIs (so the game also runs from file://)
and the bundled mods with the Python SDK. Large textures are downscaled to 128 px."""
import base64, io, json, os, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEXTURES = os.path.join(ROOT, 'assets', 'textures')
MODS = os.path.join(ROOT, 'mods')
LIMIT = 128

def encode(path):
    image = Image.open(path).convert('RGBA')
    w, h = image.size
    if max(w, h) > LIMIT:
        scale = LIMIT / max(w, h)
        image = image.resize((max(1, round(w * scale)), max(1, round(h * scale))), Image.LANCZOS)
    out = io.BytesIO()
    image.save(out, 'PNG', optimize=True)
    return 'data:image/png;base64,' + base64.b64encode(out.getvalue()).decode()

textures = {}
for folder, prefix in ((TEXTURES, ''), (os.path.join(TEXTURES, 'soft'), 'soft/')):
    for name in sorted(os.listdir(folder)):
        if name.endswith('.png'):
            textures[prefix + name] = encode(os.path.join(folder, name))

mods = {}
for name in sorted(os.listdir(MODS)):
    folder = os.path.join(MODS, name)
    if name == 'sdk' or not os.path.isdir(folder) or not os.path.isfile(os.path.join(folder, 'mod.json')):
        continue
    files = {}
    for root, _, names in os.walk(folder):
        for file in names:
            if file.endswith(('.py', '.json')) and '__pycache__' not in root:
                path = os.path.join(root, file)
                files[os.path.relpath(path, folder).replace(os.sep, '/')] = open(path, encoding='utf-8').read()
    mods[name] = files
sdk = open(os.path.join(MODS, 'sdk', 'barnocraft.py'), encoding='utf-8').read()

with open(os.path.join(ROOT, 'js', 'assets.js'), 'w', encoding='utf-8') as out:
    out.write('/* Generated by tools/build-assets.py — do not edit. */\n')
    out.write('globalThis.BC = globalThis.BC || {};\n')
    out.write('BC.TEXTURE_DATA = ' + json.dumps(textures, indent=0) + ';\n')
    out.write('BC.BUNDLED_MODS = ' + json.dumps(mods, ensure_ascii=False) + ';\n')
    out.write('BC.MOD_SDK = ' + json.dumps(sdk, ensure_ascii=False) + ';\n')
print('textures:', len(textures), 'mods:', ', '.join(mods), 'size:', os.path.getsize(os.path.join(ROOT, 'js', 'assets.js')) // 1024, 'KiB')
